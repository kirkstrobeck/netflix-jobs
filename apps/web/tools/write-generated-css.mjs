// Writes the two computed stylesheets to disk so they can be `import`ed like any
// other .css file -- which is what gets them out of the document and into a
// content-hashed, immutably cached file under /_next/static.
//
// The alternative these files replace was an inline <style> per effect. That
// shipped every byte TWICE: once as parsed HTML, and once more inside the RSC
// flight payload Next inlines into the same document, because the payload
// carries the element tree and a <style>'s CSS is just a text child of it.
//
// The generators are deterministic and take no input, so the output is a
// reproducible artifact. It is committed, and src/app/generated-css.test.ts
// fails if it ever drifts from what the generators produce.
import { writeFileSync } from "node:fs";

import "./ts-alias.mjs";

const BANNER =
  "/* Generated by tools/write-generated-css.mjs -- do not edit by hand.\n" +
  "   Retune the tunables, then run `pnpm --filter web codegen:css`. */\n";

const SHEETS = [
  {
    from: "@/app/_glow/generate-glow-css",
    name: "generateGlowCss",
    to: "../src/app/_glow/glow.generated.css",
  },
  {
    from: "@/app/_bars/generate-bars-css",
    name: "generateBarsCss",
    to: "../src/app/_bars/bars.generated.css",
  },
];

// Dynamic import, not a static one: static specifiers are resolved for the whole
// module graph before any module body runs, so an `import "@/..."` at the top of
// this file would be looked up before ./ts-alias.mjs had registered the hook.
for (const sheet of SHEETS) {
  const generator = await import(sheet.from);
  const out = new URL(sheet.to, import.meta.url);
  const css = `${BANNER}${generator[sheet.name]()}\n`;

  writeFileSync(out, css);
  console.log(`${sheet.to.replace("../", "")}  ${css.length} bytes`);
}
